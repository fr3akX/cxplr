//! Readable view of the cache for people and other agents: `.cxplr/atlas/`, one
//! Markdown page per cached map, laid out like the map hierarchy
//! (`README.md`, `<component>/README.md`, `<component>/<sub>/README.md`, …).
//! Pages are generated; they are rebuilt whole so they never drift from the cache.

use crate::cache::{Cache, Freshness};
use crate::map::{Evidence, Map};
use crate::repo::Repo;
use std::fmt::Write;
use std::fs;
use std::io;
use std::path::Path;

const MAX_CHANGED_SHOWN: usize = 10;

/// Rebuild the whole atlas; returns the number of pages written.
pub fn rebuild(repo: &Repo, cache: &Cache) -> io::Result<usize> {
    let _guard = cache.lock_atlas();
    let target = cache.dir().join("atlas");
    let tmp = cache.dir().join(format!("atlas.tmp{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp);
    fs::create_dir_all(&tmp)?;
    let mut pages = 0;
    write_scope(repo, cache, "", &mut Vec::new(), &tmp, &mut pages)?;
    let _ = fs::remove_dir_all(&target);
    if pages == 0 {
        fs::remove_dir_all(&tmp)?;
        return Ok(0);
    }
    fs::rename(&tmp, &target)?;
    Ok(pages)
}

/// `crumbs`: display names of the maps above this one, from the system down.
fn write_scope(repo: &Repo, cache: &Cache, scope: &str, crumbs: &mut Vec<String>, root: &Path, pages: &mut usize) -> io::Result<()> {
    let Some(cached) = cache.load(repo, scope) else { return Ok(()) };
    let map = &cached.map;
    let child = |id: &str| if scope.is_empty() { id.to_owned() } else { format!("{scope}/{id}") };
    let children: Vec<(String, Option<&'static str>)> =
        map.nodes.iter().map(|n| (n.id.clone(), (!n.paths.is_empty()).then(|| cache.state(repo, &child(&n.id))).flatten())).collect();

    let page = render(map, &cached.freshness, crumbs, &children);
    let dir = if scope.is_empty() { root.to_path_buf() } else { root.join(scope) };
    fs::create_dir_all(&dir)?;
    fs::write(dir.join("README.md"), page)?;
    *pages += 1;

    crumbs.push(map.title.clone());
    for (id, state) in &children {
        if state.is_some() {
            write_scope(repo, cache, &child(id), crumbs, root, pages)?;
        }
    }
    crumbs.pop();
    Ok(())
}

/// Table cells and list items must stay on one line.
fn cell(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|")
}

fn citations(evidence: &[Evidence]) -> String {
    evidence
        .iter()
        .map(|e| {
            let note = if e.note.is_empty() { String::new() } else { format!(" ({})", cell(&e.note)) };
            let flag = if e.verified { "" } else { " *unverified*" };
            format!("`{}:{}`{note}{flag}", e.path, e.line)
        })
        .collect::<Vec<_>>()
        .join("; ")
}

fn render(map: &Map, freshness: &Freshness, crumbs: &[String], children: &[(String, Option<&str>)]) -> String {
    let depth = crumbs.len();
    let up = |levels: usize| "../".repeat(levels);
    let name_of = |id: &str| map.nodes.iter().find(|n| n.id == id).map_or(id.to_owned(), |n| n.name.clone());
    let mut p = String::from("<!-- Generated by cxplr from its cache; do not edit. -->\n");
    let _ = writeln!(p, "# {}\n", map.title);

    if depth == 0 {
        p.push_str(
            "> Architecture map of this repository generated by [cxplr](https://github.com/fr3akX/cxplr). \
Start here, follow component links to go deeper. Citations are `path:line` from the repository \
root; open them before relying on a claim. A stale page describes an earlier version of the \
code: read the changed files it lists.\n\n",
        );
    } else {
        let trail: Vec<String> = crumbs.iter().enumerate().map(|(i, name)| format!("[{name}]({}README.md)", up(depth - i))).collect();
        let _ = writeln!(p, "{} › **{}**\n", trail.join(" › "), map.title);
    }

    let made = map.meta.as_ref().map(|m| {
        let commit = m.commit.as_deref().map(|c| format!(" at commit `{}`", &c[..c.len().min(10)])).unwrap_or_default();
        format!("generated{commit}{}", if m.dirty { " with uncommitted changes" } else { "" })
    });
    match freshness {
        Freshness::Fresh => {
            let _ = writeln!(p, "**Status:** fresh{}\n", made.map(|m| format!(" ({m})")).unwrap_or_default());
        }
        Freshness::Stale { changed, total, .. } => {
            let shown: Vec<String> = changed.iter().take(MAX_CHANGED_SHOWN).map(|f| format!("`{f}`")).collect();
            let more = total.saturating_sub(shown.len());
            let _ = writeln!(
                p,
                "**Status:** stale{} — {total} file{} changed since: {}{}\n",
                made.map(|m| format!(" ({m})")).unwrap_or_default(),
                if *total == 1 { "" } else { "s" },
                shown.join(", "),
                if more > 0 { format!(" and {more} more") } else { String::new() }
            );
        }
    }
    let _ = writeln!(p, "{}\n", map.summary.trim());

    p.push_str("## Components\n\n| Component | Kind | Paths | Deeper map |\n| --- | --- | --- | --- |\n");
    for (node, (_, state)) in map.nodes.iter().zip(children) {
        let paths = node.paths.iter().map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ");
        let (link, deeper) = match state {
            Some(s) => (format!("[{}]({}/README.md)", cell(&node.name), node.id), if *s == "fresh" { "yes" } else { "yes (stale)" }),
            None if node.paths.is_empty() => (cell(&node.name), "—"),
            None => (cell(&node.name), "not explored"),
        };
        let _ = writeln!(p, "| {link} | {} | {} | {deeper} |", node.kind, if paths.is_empty() { "—".into() } else { paths });
    }
    p.push('\n');
    for node in &map.nodes {
        let _ = writeln!(p, "### {}\n\n{}", node.name, node.summary.trim());
        if !node.evidence.is_empty() {
            let _ = writeln!(p, "\nEvidence: {}", citations(&node.evidence));
        }
        p.push('\n');
    }

    if !map.edges.is_empty() {
        p.push_str("## Interactions\n\n");
        for e in &map.edges {
            let ev = if e.evidence.is_empty() { String::new() } else { format!(" — {}", citations(&e.evidence)) };
            let _ = writeln!(p, "- **{} → {}** ({}): {}{ev}", name_of(&e.from), name_of(&e.to), e.kind, cell(&e.label));
        }
        p.push('\n');
    }
    if !map.flows.is_empty() {
        p.push_str("## Data flows\n\n");
        for f in &map.flows {
            let _ = writeln!(p, "### {}\n\n{}\n", f.name, f.description.trim());
            for (i, s) in f.steps.iter().enumerate() {
                let _ = writeln!(p, "{}. {} → {}: {}", i + 1, name_of(&s.from), name_of(&s.to), cell(&s.action));
            }
            p.push('\n');
        }
    }
    p
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::map::{Edge, Node};

    #[test]
    fn pages_link_explored_children_and_flag_stale_content() {
        let node = |id: &str, paths: &[&str]| Node {
            id: id.into(),
            name: format!("{id} | name"),
            kind: "module".into(),
            summary: "does\nthings".into(),
            paths: paths.iter().map(|p| (*p).to_owned()).collect(),
            evidence: vec![Evidence { path: "src/a.rs".into(), line: 3, note: String::new(), verified: false, problem: None }],
            explorable: true,
        };
        let map = Map {
            title: "Api".into(),
            summary: "The API.".into(),
            nodes: vec![node("a", &["src/a.rs"]), node("b", &["src/b"]), node("ext", &[])],
            edges: vec![Edge { from: "a".into(), to: "b".into(), kind: "call".into(), label: "x | y".into(), evidence: vec![] }],
            flows: vec![],
            diagnostics: vec![],
            meta: None,
        };
        let stale = Freshness::Stale { since: None, changed: vec!["src/b/c.rs".into()], total: 1 };
        let children = vec![("a".to_owned(), Some("fresh")), ("b".to_owned(), None), ("ext".to_owned(), None)];
        let page = render(&map, &stale, &["System".into()], &children);
        assert!(page.contains("[System](../README.md) › **Api**"));
        assert!(page.contains("**Status:** stale — 1 file changed since: `src/b/c.rs`"));
        assert!(page.contains("| [a \\| name](a/README.md) | module | `src/a.rs` | yes |"));
        assert!(page.contains("| b \\| name | module | `src/b` | not explored |"));
        assert!(page.contains("| ext \\| name | module | — | — |"));
        assert!(page.contains("`src/a.rs:3` *unverified*"));
        assert!(page.contains("- **a | name → b | name** (call): x \\| y"));
    }
}
